// Диагностика оценок игры 08.11 (только чтение, только числа и время)
import admin from 'firebase-admin';
import { decode } from './lib.mjs';
const DB_URL = 'https://fc-frohlinde-ea23f-default-rtdb.europe-west1.firebasedatabase.app';
admin.initializeApp({ credential: admin.credential.cert(JSON.parse(process.env.FIREBASE_SERVICE_ACCOUNT)), databaseURL: DB_URL });
const get = async p => (await admin.database().ref(p).get()).val();
const T = ts => ts ? new Date(ts).toLocaleString('de-DE', { timeZone: 'Europe/Berlin' }) : '–';
const raw = await get('fcf_data'); const G = decode(raw);
const blk = G.db['U19__2026/27']; const S = blk.sessions, P = blk.players.filter(Boolean);
const si = S.findIndex(s => s && s.type === 'match' && /0?8\.11/.test(s.date || ''));
const k = 'k1108-1100m';
const out = [];
const rated = P.filter(p => Array.isArray(p.rpe) && typeof p.rpe[si] === 'number');
const meta = P.map(p => p.rpeMeta && p.rpeMeta[k]).filter(Boolean);
out.push(`Оценки в данных: ${rated.length} (si=${si}); rpeMeta: ${meta.length} — ` + meta.map(m => (m.s || '?') + '@' + T(m.t)).join(', '));
const s = S[si]; const c = (s.mvp && s.mvp.c) || {};
out.push('Голосов в данных (mvp.c): ' + Object.values(c).reduce((a, v) => a + (+v || 0), 0));
const lp = Object.values(raw.auditLogP || {}).filter(e => e && (e.ts || 0) >= Date.UTC(2026, 10, 8, 12, 0));
const by = {}; lp.forEach(e => { const a = e.action || '?'; by[a] = (by[a] || 0) + 1; });
out.push('auditLogP с 08.11 13:00: ' + JSON.stringify(by));
out.push('«Belastung bewertet»: ' + lp.filter(e => e.action === 'Belastung bewertet').map(e => T(e.ts) + ' ' + (e.target || '') + ' ' + (e.detail || e.details || '')).join(' | '));
const lt = Object.values(raw.auditLogT || {}).filter(e => e && (e.ts || 0) >= Date.UTC(2026, 10, 8, 19, 0));
out.push('auditLogT с 20:00: ' + lt.map(e => T(e.ts) + ' ' + e.action).join(' | ').slice(0, 900));
out.push('последнее сохранение fcf_data: ' + T(raw._lastSaveTs) + ', приложение ' + raw._appVersion);
const fin = await get('fcf_in'); out.push('fcf_in сейчас: ' + Object.values(fin || {}).reduce((a, b) => a + Object.keys(b || {}).length, 0));
const vt = await get('fcf_vote'); let vn = 0; Object.values(vt || {}).forEach(x => { if (x && x[k]) vn++; }); out.push('fcf_vote за игру: ' + vn);
out.forEach(l => console.log(l));
console.log('::notice title=Диагностика оценок 08.11::' + out.join(' || '));
process.exit(0);
